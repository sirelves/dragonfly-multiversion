#!/usr/bin/env bash
# ids.sh: regenerates multiversion/legacy/ids.go, the packet IDs every legacy
# protocol knows, from the gophertunnel tag that shipped it.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
. "$here/lib.sh"
out=$here/../multiversion/legacy/ids.go
{
  echo "// Code generated by e2e/ids.sh from the gophertunnel tag of each protocol. DO NOT EDIT."
  echo
  echo "package legacy"
  echo
  echo "// knownIDs holds, per protocol, every packet ID its client can decode."
  echo "var knownIDs = map[int32][]uint32{"
  for p in $(e2e_protos); do
    [ "$p" -ge 589 ] && continue
    e2e_build_verifier "$p" >&2
    printf '\t%s: {%s},\n' "$p" "$("$here/bin/verify-$p" -ids | paste -sd, - | sed 's/,/, /g')"
  done
  echo "}"
} > "$out.tmp"
mv "$out.tmp" "$out"
gofmt -w "$out"
echo "wrote $out"
