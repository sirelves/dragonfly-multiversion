#!/usr/bin/env python3
"""command_args.py <gophertunnel clone> <versions.txt> <out.go>

Command parameter type IDs move between protocols. gophertunnel names them the
same in every tag (CommandArgType*), so the IDs of 589 (what v649 hands to the
legacy protocols) map onto each older tag's by name. A type the older protocol
does not have becomes its String type: the client then takes free text.
"""
import re, subprocess, sys

gt, versions, out = sys.argv[1:4]

def consts(tag):
    src = subprocess.run(["git", "-C", gt, "show", tag + ":minecraft/protocol/command.go"], capture_output=True, text=True, check=True).stdout
    return {m.group(1): int(m.group(2)) for m in re.finditer(r"CommandArgType(\w+)\s*=\s*(\d+)", src)}

rows = [l.split() for l in open(versions) if l.strip() and not l.startswith("#")]
base = consts(dict((r[0], r[1]) for r in rows)["589"])
lines = ["// Code generated by cmd/mvgen/command_args.py from gophertunnel's tags. DO NOT EDIT.", "",
         "package legacy", "",
         "// commandArgTypes maps, per protocol, the command parameter type IDs of 589 to",
         "// that protocol's. Types it lacks become its String type.",
         "var commandArgTypes = map[int32]map[uint32]uint32{"]
for proto, tag, *_ in rows:
    if int(proto) >= 589:
        continue
    old = consts(tag)
    m = {}
    for name, i in base.items():
        j = old.get(name, old["String"])
        if j != i:
            m[i] = j
    lines.append("\t%s: {%s}," % (proto, ", ".join("%d: %d" % (k, m[k]) for k in sorted(m))))
    print(proto, tag, "types:", len(old), "remapped:", len(m))
lines.append("}")
open(out, "w").write("\n".join(lines) + "\n")
